// Generate scoped dark overrides without changing the approved light styles.
// Run after adding palette colors to a page: node scripts/generate-dark-theme.mjs
import fs from 'node:fs';
import postcss from 'postcss';
const files = ['src/index.css', ...fs.readdirSync('src/pages').filter(f=>f.endsWith('.css')).map(f=>`src/pages/${f}`), ...fs.readdirSync('src/components').filter(f=>f.endsWith('.css')).map(f=>`src/components/${f}`)];
// Match the actual cascade: base styles before their editorial refinements.
files.sort((a,b)=> {
 const order = ['index.css','auth.css','login.css','dashboard.css','crypto-market.css','home.css','visual-sections.css','login-editorial.css','dashboard-editorial.css','transactions.css','funding.css'];
 return order.indexOf(a.split('/').pop())-order.indexOf(b.split('/').pop());
});
function color(hex, role) {
 let h=hex.slice(1); if(h.length<=4) h=[...h].map(c=>c+c).join('');
 const r=parseInt(h.slice(0,2),16),g=parseInt(h.slice(2,4),16),b=parseInt(h.slice(4,6),16);
 const l=(r*.2126+g*.7152+b*.0722)/255;
 let rgb;
 if(role==='surface') {
  // Preserve dark photo overlays and forest CTA surfaces.
  if(l<.32) return hex;
  rgb=l>.96?[24,36,30]:l>.90?[20,31,26]:l>.78?[31,45,36]:l>.60?[42,59,46]:[52,76,57];
 } else if(role==='border') rgb=l>.65?[54,74,60]:[70,94,76];
 else {
  if(l>.88) return hex;
  const red=r>g*1.22 && r>b*1.15, gold=r>g*1.12 && g>b*1.2;
  rgb=red?[240,160,147]:gold?[217,185,135]:l<.4?[220,231,214]:[163,183,158];
 }
 return '#'+rgb.map(n=>n.toString(16).padStart(2,'0')).join('')+(h.length===8?h.slice(6):'');
}
const root=postcss.root();
for(const file of files){
 const ast=postcss.parse(fs.readFileSync(file,'utf8'));
 function walk(container,out){for(const node of container.nodes||[]){
  if(node.type==='atrule' && ['media','supports','layer'].includes(node.name)){const at=postcss.atRule({name:node.name,params:node.params});walk(node,at);if(at.nodes?.length)out.append(at);}
  if(node.type!=='rule')continue;
  const rule=postcss.rule({selector:node.selectors.map(s=>`:root[data-theme="dark"] ${s === ':root' || s === 'html' ? '' : s}`).join(',')});
  for(const decl of node.nodes||[]){
   if(decl.type!=='decl')continue;
   const p=decl.prop;
   if(!/color|background|border|fill|stroke|^--/.test(p)||/image|shadow/.test(p))continue;
   let role=/background/.test(p)?'surface':/border/.test(p)?'border':'text';
   if(p.startsWith('--'))role=/paper|cream|soft|navy|blue|lime|green/.test(p)?'surface':'text';
   const value=decl.value.replace(/#[\da-f]{3,8}\b/gi,h=>color(h,role)).replace(/\bwhite\b/g,role==='surface'?'#18241e':'#fff').replace(/\bblack\b/g,role==='text'?'#dce7d6':'#000');
   if(value!==decl.value)rule.append({prop:p,value,important:decl.important});
  }
  if(rule.nodes?.length)out.append(rule);
 }}
 walk(ast,root);
}
fs.writeFileSync('src/dark-palette.css','/* Generated by scripts/generate-dark-theme.mjs. Scoped; light mode is unchanged. */\n'+root.toString());
